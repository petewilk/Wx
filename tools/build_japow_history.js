// Builds japow_history.js (past seasons of daily max snow depth per station) from JMA's past-data pages.
// Usage: node tools/build_japow_history.js [firstSeason] [lastSeason]
// Defaults to 1991 through the last finished season. Raw pages are cached in $TMPDIR/japow-etrn-cache,
// so a rerun only fetches what is new. Rerun each summer to add the season that just ended.
var fs = require('fs'), path = require('path'), os = require('os');
var J = require('../japow.js');

var now = new Date();
var lastFinished = J.seasonOf(now.getUTCFullYear(), now.getUTCMonth() + 1) - 1;   // the running season is live-loaded
var FIRST = +process.argv[2] || 1991;
var LAST = +process.argv[3] || lastFinished;
var CACHE = path.join(os.tmpdir(), 'japow-etrn-cache');
var OUT = path.join(__dirname, '..', 'japow_history.js');
var CONCURRENCY = 3, PAUSE_MS = 150;   // stay gentle with JMA

fs.mkdirSync(CACHE, { recursive: true });

function sleep(ms) { return new Promise(function(r) { setTimeout(r, ms); }); }

async function getPage(st, y, m) {
  var f = path.join(CACHE, st.prec + '_' + st.block + '_' + y + '_' + m + '.html');
  if (fs.existsSync(f)) return fs.readFileSync(f, 'utf8');
  for (var attempt = 1; ; attempt++) {
    try {
      var res = await fetch(J.etrnUrl(st, y, m));
      if (!res.ok) throw new Error('HTTP ' + res.status);
      var html = await res.text();
      fs.writeFileSync(f, html);
      await sleep(PAUSE_MS);
      return html;
    } catch (e) {
      if (attempt >= 4) throw e;
      await sleep(1000 * attempt);
    }
  }
}

async function main() {
  var jobs = [];
  Object.keys(J.JAPOW_STATIONS).forEach(function(id) {
    for (var s = FIRST; s <= LAST; s++) {
      J.SEASON_MONTHS.forEach(function(m) { jobs.push({ id: id, s: s, m: m }); });
    }
  });
  var depth = {}, done = 0;
  async function worker() {
    for (var job; (job = jobs.shift()); ) {
      var st = J.JAPOW_STATIONS[job.id], y = J.monthYear(job.s, job.m);
      var rows = J.parseEtrnDaily(await getPage(st, y, job.m), st.kind);
      depth[job.id] = depth[job.id] || {};
      var arr = depth[job.id][job.s] = depth[job.id][job.s] || new Array(J.SEASON_DAYS).fill(null);
      J.placeMonth(rows, job.s, y, job.m, arr);
      if (++done % 100 === 0) process.stderr.write(done + ' pages\n');
    }
  }
  var total = jobs.length;
  process.stderr.write('Fetching ' + total + ' pages (' + FIRST + '-' + LAST + ' seasons)\n');
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // Keep a season only if most of its days have a depth reading (sensor existed and worked)
  var stations = {};
  Object.keys(depth).forEach(function(id) {
    stations[id] = {};
    Object.keys(depth[id]).sort().forEach(function(s) {
      var a = depth[id][s], n = a.filter(function(v) { return v != null; }).length;
      if (n >= J.SEASON_DAYS * 0.8) stations[id][s] = a;
    });
    var ks = Object.keys(stations[id]);
    process.stderr.write(J.JAPOW_STATIONS[id].n + ': ' + ks.length + ' seasons' + (ks.length ? ' (' + ks[0] + '-' + ks[ks.length - 1] + ')' : '') + '\n');
  });

  var body = Object.keys(stations).map(function(id) {
    return '  ' + id + ': {\n' + Object.keys(stations[id]).map(function(s) {
      return '    ' + s + ': ' + JSON.stringify(stations[id][s]);
    }).join(',\n') + '\n  }';
  }).join(',\n');
  fs.writeFileSync(OUT,
    '// Generated by tools/build_japow_history.js on ' + now.toISOString().slice(0, 10) + ' from JMA past data (etrn).\n' +
    '// Daily max snow depth (cm), Nov 1 - May 31, by station and season start year. Do not edit by hand.\n' +
    'var JAPOW_HISTORY = {\n' + body + '\n};\n' +
    "if (typeof module !== 'undefined' && module.exports) module.exports = JAPOW_HISTORY;\n");
  process.stderr.write('Wrote ' + OUT + '\n');
}

main().catch(function(e) { console.error(e); process.exit(1); });
